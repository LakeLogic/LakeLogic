"""Generate docs/contracts/lint_rules.md from lakelogic.core.contract_lint_catalogue.

    python scripts/generate_lint_catalogue.py          # write the page
    python scripts/generate_lint_catalogue.py --check  # exit 1 if the page is stale

The page is what an LLM (or a person) reads to learn why each `lakelogic lint` rule exists and
what a correct contract looks like. Every example on it is proven by
tests/test_contract_lint_catalogue.py, so the page cannot teach something the linter disagrees with.
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from lakelogic.core.contract_lint_catalogue import CATALOGUE  # noqa: E402

OUT = ROOT / "docs" / "contracts" / "lint_rules.md"

_GROUPS = [
    ("Keys and deduplication", ["PK-002", "KEY-001", "KEY-002", "KEY-003"]),
    ("Transformations and rule phases", ["TRF-001", "PHS-001"]),
    ("Personal and sensitive data", ["PII-001", "PII-002", "SENS-001"]),
    ("Loads, deletes and history", ["DEL-001", "SCD-001", "SRC-001", "STREAM-001", "STREAM-002"]),
    ("Quality and service levels", ["QLT-001", "VOL-001"]),
    ("Ownership", ["OWN-001", "OWN-002"]),
]


def _anchor(code: str) -> str:
    return code.lower()


def render() -> str:
    grouped = [c for _, codes in _GROUPS for c in codes]
    missing = sorted(set(CATALOGUE) - set(grouped))
    if missing:
        raise SystemExit(f"rules not placed in a group in {Path(__file__).name}: {missing}")

    lines = [
        "<!-- Generated by scripts/generate_lint_catalogue.py from lakelogic/core/contract_lint_catalogue.py."
        " Do not edit by hand. -->",
        "",
        "# Lint rules",
        "",
        "`lakelogic lint` reviews a contract for governance gaps: missing keys, unordered deduplication,",
        "untagged personal data, steps that never run. Each rule below says what it checks, **why it",
        "matters**, a contract that fails it and the smallest fix.",
        "",
        "Every example on this page is run through the linter in LakeLogic's test suite: the failing",
        "example raises exactly that rule, and the fixed example raises none. Fixed examples are valid",
        "[OLC](https://lakelogic.github.io/open-lakehouse-contract/) contracts unless marked otherwise.",
        "",
        "```bash",
        "lakelogic lint contracts/",
        "```",
        "",
        "| Rule | Severity | What it catches |",
        "|---|---|---|",
    ]
    for _, codes in _GROUPS:
        for code in codes:
            e = CATALOGUE[code]
            lines.append(f"| [{code}](#{_anchor(code)}) | {e.severity} | {e.title} |")
    lines.append("")

    for group, codes in _GROUPS:
        lines += [f"## {group}", ""]
        for code in codes:
            e = CATALOGUE[code]
            lines += [
                f"### {code}: {e.title} {{ #{_anchor(code)} }}",
                "",
                f"**Severity:** {e.severity}  ",
                f"**Checks:** {e.checks}",
                "",
                f"**Why it matters.** {e.why}",
                "",
            ]
            if e.context:
                lines += [
                    "This rule is judged against the domain's resolved policy "
                    "(`_domain.yaml` / `_system.yaml`), not the contract alone.",
                    "",
                ]
            lines += [
                "**Fails:**",
                "",
                "```yaml",
                e.failing.rstrip(),
                "```",
                "",
                "**Fixed:**",
                "",
                "```yaml",
                e.fixed.rstrip(),
                "```",
                "",
            ]
            if not e.olc_valid:
                lines += [
                    "!!! note",
                    "    The fix uses a LakeLogic runtime setting that the OLC standard does not define.",
                    "",
                ]
    return "\n".join(lines).rstrip() + "\n"


def main(argv: list[str]) -> int:
    text = render()
    if "--check" in argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print(f"{OUT.relative_to(ROOT)} is stale: run python scripts/generate_lint_catalogue.py")
            return 1
        print(f"{OUT.relative_to(ROOT)} is up to date")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(CATALOGUE)} rules)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
