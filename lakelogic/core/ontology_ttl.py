"""Write the business ontology as RDF Turtle, one file per domain.

``lakelogic ontology contracts/ --format ttl`` writes ``ontology/<domain>.ttl`` (a folder beside
``contracts/``, kept apart because these files are generated, not authored) and
``ontology/index.ttl``, which imports them. The files are
GENERATED: names and definitions are edited in ``_domain.yaml`` and the contracts, and the Turtle
follows. Everything comes from :func:`lakelogic.core.business_map.derive_business_map`, the
same reading the platform's Business ontology page draws, so the file and the page agree.

Vocabulary (RDF 1.1 Turtle, so current tools read it):

* a domain is a ``skos:ConceptScheme``;
* a concept is an ``owl:Class`` and a ``skos:Concept`` — ``skos:prefLabel``, ``skos:definition``,
  ``skos:altLabel`` (``also_called``), ``ll:identifierColumn`` (each column of the key, in order),
  ``ll:sourceContract``, ``ll:hasDetail`` (code lookups such as Cabin), ``ll:evidence``;
* a link is an ``owl:ObjectProperty`` with ``rdfs:domain`` / ``rdfs:range``, ``ll:foundBy`` (how
  Core knows it), ``ll:joinKey``, ``ll:sourceContract`` and ``ll:evidence``. It is written in the
  file of the domain that owns its ``from`` concept and names the other concept by its IRI;
* a declared metric is an ``ll:Metric`` with ``ll:measures`` (its concept), ``ll:expression``,
  ``ll:unit``, ``ll:additivity`` and ``ll:sourceContract``, written beside the concept it measures.
  Only metrics a contract declares: none is inferred here (ontology-metrics-v1).

Evidence: ``ll:Observed`` (the contracts state it), ``ll:Suggested`` (plausible only) and
``ll:Confirmed`` (the owning domain approved its meaning). Suggested concepts and links are left
out unless ``include_suggested`` — a tool reading the file treats every statement as fact.
Output is sorted, so a regenerated file diffs only where the ontology changed.
"""

from __future__ import annotations

import os
import re
from typing import Any, Dict, Iterable, List, Optional, Tuple

__all__ = ["render_domain_ttl", "render_index_ttl", "write_domain_ttl", "DEFAULT_BASE"]

DEFAULT_BASE = "urn:lakelogic:ontology:"
LL = "https://lakelogic.org/ns/ontology#"
HEADER = (
    "# Generated by LakeLogic from the data contracts and _domain.yaml. Do not edit this file:\n"
    "# change names and definitions in _domain.yaml (or the contracts) and regenerate.\n"
)
PREFIXES = {
    "owl": "http://www.w3.org/2002/07/owl#",
    "rdfs": "http://www.w3.org/2000/01/rdf-schema#",
    "skos": "http://www.w3.org/2004/02/skos/core#",
    "ll": LL,
}
_EVIDENCE = {"observed": "ll:Observed", "suggested": "ll:Suggested", "confirmed": "ll:Confirmed"}
_RANK = {"suggested": 0, "observed": 1, "confirmed": 2}


def _lit(value: str) -> str:
    """A Turtle string literal (short form, escaped)."""
    s = (
        str(value)
        .replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("\n", "\\n")
        .replace("\r", "\\r")
        .replace("\t", "\\t")
    )
    return f'"{s}"'


def _local(name: str) -> str:
    """A safe IRI local part: Driver licence -> DriverLicence, fx_rate -> FxRate."""
    parts = re.split(r"[^0-9A-Za-z]+", name)
    out = "".join(p[:1].upper() + p[1:] for p in parts if p)
    return out if out and not out[0].isdigit() else f"C{out}"


def _slug(domain: str) -> str:
    return re.sub(r"[^0-9a-z]+", "-", (domain or "unassigned").lower()).strip("-") or "unassigned"


def _owning_domain(e: Dict[str, Any]) -> str:
    for c in e.get("contracts") or []:
        if c.get("layer") == "silver" and c.get("domain"):
            return c["domain"]
    if e.get("domains"):
        return e["domains"][0]
    return next((c["domain"] for c in e.get("contracts") or [] if c.get("domain")), None) or "unassigned"


def _evidence(item: Dict[str, Any], key: str) -> str:
    return item.get("evidence_state") or "suggested"


def _scheme(base: str, domain: str) -> str:
    return f"<{base}{_slug(domain)}/>"


def _iri(base: str, domain: str, local: str) -> str:
    return f"<{base}{_slug(domain)}/{local}>"


def _concepts(
    business_map: Dict[str, Any], include_suggested: bool
) -> Tuple[Dict[str, Dict[str, Any]], Dict[str, str]]:
    """Concepts to write (not lookups; with a contract or confirmed), and each one's domain."""
    keep: Dict[str, Dict[str, Any]] = {}
    owner: Dict[str, str] = {}
    for e in business_map.get("entities") or []:
        if e.get("attribute_of"):
            continue
        if not e.get("contracts") and e.get("state") != "confirmed":
            continue
        if not include_suggested and _evidence(e, "concept") == "suggested":
            continue
        keep[e["name"]] = e
        owner[e["name"]] = _owning_domain(e)
    return keep, owner


def _block(subject: str, pairs: Iterable[Tuple[str, str]]) -> str:
    rows = [(p, o) for p, o in pairs if o]
    lines = [subject]
    for i, (p, o) in enumerate(rows):
        lines.append(f"    {p} {o}{' .' if i == len(rows) - 1 else ' ;'}")
    return "\n".join(lines)


def render_domain_ttl(
    business_map: Dict[str, Any],
    domain: str,
    base: str = DEFAULT_BASE,
    include_suggested: bool = False,
) -> str:
    """The Turtle for one domain: its scheme, the concepts it owns and the links leaving them."""
    concepts, owner = _concepts(business_map, include_suggested)
    mine = sorted(n for n, d in owner.items() if d == domain)
    details: Dict[str, List[str]] = {}
    for e in business_map.get("entities") or []:
        for parent in e.get("attribute_of") or []:
            details.setdefault(parent, []).append(e["name"])

    out = [HEADER]
    for p, iri in PREFIXES.items():
        out.append(f"@prefix {p}: <{iri}> .")
    out.append("")
    out.append(
        _block(
            _scheme(base, domain),
            [
                ("a", "skos:ConceptScheme"),
                ("skos:prefLabel", _lit(domain.replace("_", " ").title())),
            ],
        )
    )
    for name in mine:
        e = concepts[name]
        pairs: List[Tuple[str, str]] = [
            ("a", "owl:Class, skos:Concept"),
            ("skos:inScheme", _scheme(base, domain)),
            ("skos:prefLabel", _lit(name)),
        ]
        if e.get("definition"):
            pairs.append(("skos:definition", _lit(e["definition"])))
        also = sorted(set(e.get("also_called") or []))
        if also:
            pairs.append(("skos:altLabel", ", ".join(_lit(a) for a in also)))
        cols = e.get("identifier_columns") or ([e["identifier"]] if e.get("identifier") else [])
        if cols:
            pairs.append(("ll:identifierColumn", ", ".join(_lit(c) for c in cols)))
        sources = sorted({c["name"] for c in e.get("contracts") or [] if c.get("name")})
        if sources:
            pairs.append(("ll:sourceContract", ", ".join(_lit(s) for s in sources)))
        if details.get(name):
            pairs.append(("ll:hasDetail", ", ".join(_lit(d) for d in sorted(details[name]))))
        pairs.append(("ll:evidence", _EVIDENCE[_evidence(e, "concept")]))
        out.append("")
        out.append(_block(_iri(base, domain, _local(name)), pairs))
        for m in sorted(e.get("metrics") or [], key=lambda x: (x["name"].lower(), x["contract"])):
            mpairs: List[Tuple[str, str]] = [
                ("a", "ll:Metric"),
                ("rdfs:label", _lit(m["name"])),
                ("ll:measures", _iri(base, domain, _local(name))),
                ("ll:expression", _lit(m["expression"])),
            ]
            if m.get("unit"):
                mpairs.append(("ll:unit", _lit(m["unit"])))
            mpairs.append(("ll:additivity", _lit(m.get("additivity") or "additive")))
            if m.get("description"):
                mpairs.append(("rdfs:comment", _lit(m["description"])))
            mpairs.append(("ll:sourceContract", _lit(m["contract"])))
            out.append("")
            out.append(_block(_iri(base, domain, f"{_local(name)}_metric_{_local(m['name'])}_{_local(m['contract'])}"), mpairs))

    links = []
    for r in business_map.get("relationships") or []:
        a, b = r.get("from"), r.get("to")
        if a not in concepts or b not in concepts or a == b or owner.get(a) != domain:
            continue
        if r.get("kind") == "name_only" and not include_suggested:
            continue
        ev = _evidence(r, "link")
        if not include_suggested and ev == "suggested":
            continue
        links.append(r)
    for r in sorted(links, key=lambda x: (x["from"], x["to"])):
        a, b = r["from"], r["to"]
        verb = r.get("verb") or "relates to"
        evidence = r.get("evidence") or []
        key = next((x.get("column") for x in evidence if x.get("column")), None)
        sources = sorted({x["contract"] for x in evidence if x.get("contract")})
        pairs = [
            ("a", "owl:ObjectProperty"),
            ("rdfs:label", _lit(f"{a} {verb} {b}")),
            ("rdfs:domain", _iri(base, owner[a], _local(a))),
            ("rdfs:range", _iri(base, owner[b], _local(b))),
            ("ll:foundBy", _lit(r.get("kind") or "")),
            ("ll:joinKey", _lit(key) if key else ""),
            ("ll:sourceContract", ", ".join(_lit(s) for s in sources)),
            ("ll:evidence", _EVIDENCE[_evidence(r, "link")]),
        ]
        if r.get("cardinality") and r["cardinality"] != "unknown":
            pairs.append(("ll:cardinality", _lit(r["cardinality"])))
        out.append("")
        out.append(_block(_iri(base, domain, f"{_local(a)}_to_{_local(b)}"), pairs))
    return "\n".join(out) + "\n"


def render_index_ttl(domains: Iterable[str], base: str = DEFAULT_BASE) -> str:
    """The root file: one ontology importing every domain's file."""
    out = [HEADER, "@prefix owl: <http://www.w3.org/2002/07/owl#> .", ""]
    doms = sorted(set(domains))
    rows = [("a", "owl:Ontology")] + [("owl:imports", _scheme(base, d)) for d in doms]
    out.append(_block(f"<{base}>", rows))
    return "\n".join(out) + "\n"


def write_domain_ttl(
    root: str,
    out_dir: Optional[str] = None,
    base: str = DEFAULT_BASE,
    include_suggested: bool = False,
    domains: Optional[Iterable[str]] = None,
) -> List[str]:
    """Write ``<domain>.ttl`` for each domain and ``index.ttl`` into ``out_dir`` (default: an
    ``ontology`` folder beside ``root``). Returns the paths written."""
    from lakelogic.core.business_map import derive_business_map
    from lakelogic.core.ontology_render import load_contract_folder

    docs = load_contract_folder(root)
    business_map = derive_business_map(docs, _domain_files(root) or None)
    concepts, owner = _concepts(business_map, include_suggested)
    wanted = {d.lower() for d in domains} if domains else None
    all_domains = sorted({d for d in owner.values() if wanted is None or d.lower() in wanted})
    target = out_dir or os.path.join(os.path.dirname(os.path.abspath(root.rstrip("/\\"))), "ontology")
    os.makedirs(target, exist_ok=True)
    written = []
    for d in all_domains:
        path = os.path.join(target, f"{_slug(d)}.ttl")
        with open(path, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(render_domain_ttl(business_map, d, base, include_suggested))
        written.append(path)
    index = os.path.join(target, "index.ttl")
    with open(index, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(render_index_ttl(all_domains, base))
    written.append(index)
    return written


def _domain_files(root: str) -> Dict[str, Dict[str, Any]]:
    """``_domain.yaml`` per top-level domain folder, so confirmed concepts are included."""
    import yaml

    out: Dict[str, Dict[str, Any]] = {}
    for name in sorted(os.listdir(root)) if os.path.isdir(root) else []:
        path = os.path.join(root, name, "_domain.yaml")
        if os.path.isfile(path):
            try:
                with open(path, encoding="utf-8") as fh:
                    doc = yaml.safe_load(fh)
                if isinstance(doc, dict):
                    out[name] = doc
            except Exception:  # noqa: BLE001 - an unreadable domain file is skipped
                continue
    return out
