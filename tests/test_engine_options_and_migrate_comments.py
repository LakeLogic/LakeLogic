"""`source.options.engine_options` reaches the Spark reader, and `migrate-options` rewrites a
file without losing comments or re-indenting it.

Found on 2026-10-13 migrating the Databricks RideFlow demo (28 contracts): nothing read
`engine_options`, the migration dropped a two-line comment, and it re-indented every list.
"""

from loguru import logger
from typer.testing import CliRunner

from lakelogic.cli.main import app
from lakelogic.core.processor import (
    _apply_spark_engine_options,
    _engine_options,
    _warn_engine_options_unused,
)


class _Source:
    def __init__(self, options):
        self.options = options


class _Reader:
    """Records `.option()` calls in order, like a Spark DataFrameReader."""

    def __init__(self):
        self.calls = []

    def option(self, key, value):
        self.calls.append((key, value))
        return self


# ── engine_options ──────────────────────────────────────────────────────────────


def test_engine_options_reach_the_spark_reader_as_written():
    src = _Source({"has_header": True, "engine_options": {"mergeSchema": "true", "maxFilesPerTrigger": 5}})
    reader = _apply_spark_engine_options(_Reader(), src)
    assert reader.calls == [("mergeSchema", "true"), ("maxFilesPerTrigger", 5)]


def test_a_declared_option_set_afterwards_still_decides():
    # The framework sets its own reader options AFTER this call; the later `.option()` wins in Spark.
    reader = _apply_spark_engine_options(_Reader(), _Source({"engine_options": {"header": "false"}}))
    reader = reader.option("header", "true")  # what the CSV branch does next
    assert reader.calls[-1] == ("header", "true")


def test_no_engine_options_means_no_reader_calls():
    for options in (None, {}, {"has_header": True}, {"engine_options": None}, {"engine_options": "x"}):
        assert _engine_options(_Source(options)) == {}
        assert _apply_spark_engine_options(_Reader(), _Source(options)).calls == []


def test_another_engine_says_it_does_not_use_them():
    seen = []
    sink = logger.add(lambda m: seen.append(str(m)), level="WARNING")
    try:
        src = _Source({"engine_options": {"recursiveFileLookup": "true", "header": "true"}})
        _warn_engine_options_unused(src, "polars")
        _warn_engine_options_unused(src, "spark")  # applied there: nothing to say
        _warn_engine_options_unused(_Source({}), "polars")  # nothing declared: nothing to say
    finally:
        logger.remove(sink)
    assert len(seen) == 1
    assert "header, recursiveFileLookup" in seen[0] and "polars" in seen[0]


# ── migrate-options: comments and indentation ───────────────────────────────────

INDENTED = """\
version: 1.0.0
info:
  title: dim date   # the calendar
model:
  fields:
    - name: date_key
      type: int
    - name: full_date
      type: date
quality:
  dataset_rules:
    - unique: date_key
source:
  type: landing
  path: "{landing_root}/dim_date_seed"
  format: csv
  options:
    header: "true"
  # Stays full (deliberate): the rows are generated by external_logic,
  # not read from a source, so there is nothing to watermark.
  load_mode: full
"""

FLUSH = """\
version: 1.0.0
info:
  title: flush
model:
  fields:
  - name: a
    type: string
source:
  type: landing
  path: "{landing_root}/a"
  format: csv
  options:
    recursiveFileLookup: "true"
    # between two options
    delimiter: ";"
  load_mode: full
"""


def _migrate(tmp_path, text):
    path = tmp_path / "c.yaml"
    path.write_text(text, encoding="utf-8")
    out = CliRunner().invoke(app, ["migrate-options", str(path), "--write"])
    assert out.exit_code == 0, out.output
    return path.read_text(encoding="utf-8"), out.output


def _changed(before, after):
    import difflib

    return [
        line
        for line in difflib.unified_diff(before.splitlines(), after.splitlines(), lineterm="", n=0)
        if line[:1] in "+-" and line[:3] not in ("+++", "---")
    ]


def test_a_comment_after_a_moved_option_is_kept_where_it_was(tmp_path):
    after, output = _migrate(tmp_path, INDENTED)
    assert "could not be kept" not in output
    assert "# the calendar" in after
    # The note still sits between the options block and load_mode.
    block = after[after.index("  options:") :]
    assert (
        block.index("header:")
        < block.index("# Stays full (deliberate)")
        < block.index("# not read from")
        < block.index("load_mode:")
    )


def test_only_the_migrated_lines_change(tmp_path):
    after, _ = _migrate(tmp_path, INDENTED)
    assert _changed(INDENTED, after) == [
        '-    header: "true"',
        "+    engine_options:",
        '+      header: "true"',
    ]


def test_a_file_with_flush_lists_keeps_them_flush_and_its_mid_block_comment(tmp_path):
    after, output = _migrate(tmp_path, FLUSH)
    assert "could not be kept" not in output
    assert "\n  - name: a\n" in after  # not re-indented to "    - name: a"
    assert "# between two options" in after
    changed = _changed(FLUSH, after)
    assert all("name: a" not in line and "type: string" not in line for line in changed), changed
