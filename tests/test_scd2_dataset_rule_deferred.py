"""A dataset rule over an SCD2-injected column must not be evaluated during validation.

`quality.dataset_rules: [- unique: driver_sk]` compiles to

    SELECT COUNT(*) - COUNT(DISTINCT driver_sk) FROM {dataset}    (expected < 1.0)

but `driver_sk` is the SCD2 SURROGATE KEY, generated by the materializer — which runs
AFTER validation. At rule time the column is present (it is declared in `model.fields`) and
entirely NULL, so `COUNT(DISTINCT driver_sk)` is 0 and the expression returns the ROW COUNT.

The rule therefore cannot pass, and it fails with a number that looks like evidence. Seen on
the live RideFlow estate as

    driver_sk_unique | Result: 249 (expected < 1.0) | FAIL

on a run where all 249 rows were valid, and `2042 (expected < 1.0)` on a bigger one. The
"duplicate count" always equals the row count — that equality is the tell.

The damage is not cosmetic: `failed_rules > 0` pins the product to Degraded/Failing
permanently, and a gate that can never pass trains people to ignore gates.

`_scd2_injected_columns()` already existed for precisely this, and its docstring says so —
"checks that run BEFORE materialization ... must treat them as derived — not missing". The
schema-drift path consulted it; the dataset-rule path did not.

DEFERRED, not passed. Recording such a rule as passing would assert a uniqueness that this
run never checked — which is the same class of lie as failing it.
"""

from __future__ import annotations

from types import SimpleNamespace

import pytest

from lakelogic.engines.base import EngineAdapter


def _rule(name: str, sql: str):
    return SimpleNamespace(name=name, sql=sql, description=None)


def _injected() -> set:
    """What `_scd2_injected_columns()` returns for the RideFlow dim-driver contract."""
    return {"driver_sk", "effective_from", "effective_to", "is_current", "version_number"}


def test_a_rule_over_the_surrogate_key_is_recognised_as_deferred():
    """The exact rule that has been failing every run since it was written."""
    rule = _rule("driver_sk_unique", "SELECT COUNT(*) - COUNT(DISTINCT driver_sk) FROM dim_driver")
    assert EngineAdapter._rule_targets_deferred_column(rule, _injected()) == "driver_sk"


@pytest.mark.parametrize("column", ["effective_from", "effective_to", "is_current", "version_number"])
def test_every_scd2_control_column_is_recognised(column):
    """Not just the surrogate key — the materializer injects all of these."""
    rule = _rule(f"{column}_check", f"SELECT COUNT(*) FROM t WHERE {column} IS NULL")
    assert EngineAdapter._rule_targets_deferred_column(rule, _injected()) == column


def test_an_ordinary_rule_is_left_alone():
    """A rule over a real source column must still run. This is the guard on the guard:
    a fix that deferred everything would silence quality checks estate-wide."""
    rule = _rule("driver_id_unique", "SELECT COUNT(*) - COUNT(DISTINCT driver_id) FROM dim_driver")
    assert EngineAdapter._rule_targets_deferred_column(rule, _injected()) is None


def test_matching_is_on_word_boundaries_not_substrings():
    """`driver_sk` must not swallow a rule about a DIFFERENT column that contains it.

    A naive `if col in sql` defers `prev_driver_sk` and `driver_sk_backup` too — real
    columns the materializer does not touch, whose rules would then silently stop running.
    """
    for other in ("prev_driver_sk", "driver_sk_backup"):
        rule = _rule(f"{other}_unique", f"SELECT COUNT(*) - COUNT(DISTINCT {other}) FROM t")
        assert EngineAdapter._rule_targets_deferred_column(rule, _injected()) is None, other


def test_nothing_is_deferred_when_the_contract_is_not_scd2():
    """`_scd2_injected_columns()` returns an empty set for every other strategy, and an
    empty set must defer nothing at all."""
    rule = _rule("driver_sk_unique", "SELECT COUNT(*) - COUNT(DISTINCT driver_sk) FROM t")
    assert EngineAdapter._rule_targets_deferred_column(rule, set()) is None
