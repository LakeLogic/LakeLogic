"""Business ontology as Turtle: one file per domain, generated, evidence-filtered, sorted."""

from __future__ import annotations

import copy

from typer.testing import CliRunner

from lakelogic.cli.main import app
from lakelogic.core.business_map import derive_business_map
from lakelogic.core.ontology_ttl import render_domain_ttl, render_index_ttl


def _c(name, key, fields, system, domain, description=None, **extra):
    c = {"name": name, "system": system, "_domain": domain, "primary_key": key,
         "model": {"fields": [{"name": f} for f in fields]}, "info": {"title": name}}
    if description:
        c["info"]["description"] = description
    c.update(extra)
    return c


ESTATE = [
    _c("silver_rideflow_driver_profiles", ["driver_id"], ["driver_id", "city_code"], "rideflow", "marketplace",
       description='A "driver" on the platform.\nOne row per driver.'),
    _c("silver_rideflow_trips", ["trip_id"], ["trip_id", "driver_id"], "rideflow", "marketplace"),
    _c("silver_stripe_payouts", ["payout_id"], ["payout_id", "driver_id"], "stripe", "payments"),
    _c("gold_dim_driver_profiles", ["driver_sk"], ["driver_sk", "driver_id"], "rideflow", "marketplace"),
    _c("gold_fact_payouts", ["payout_id"], ["payout_id", "driver_sk"], "stripe", "payments"),
]


def test_core_sets_one_evidence_state_for_concepts_and_links():
    m = derive_business_map(copy.deepcopy(ESTATE))
    assert {e["evidence_state"] for e in m["entities"]} <= {"observed", "suggested", "confirmed"}
    assert {r["evidence_state"] for r in m["relationships"]} <= {"observed", "suggested", "confirmed"}
    for r in m["relationships"]:
        if r["kind"] in ("join", "foreign_key", "sql_join"):
            assert r["evidence_state"] in ("observed", "confirmed")
        if r["kind"] == "name_only":
            assert r["evidence_state"] == "suggested"


def test_domain_file_holds_its_concepts_and_links_leaving_them():
    m = derive_business_map(copy.deepcopy(ESTATE))
    ttl = render_domain_ttl(m, "marketplace", base="https://x.example/o/")
    assert ttl.startswith("# Generated by LakeLogic")
    assert "<https://x.example/o/marketplace/Driver>" in ttl
    assert "a owl:Class, skos:Concept" in ttl
    assert 'll:identifierColumn "driver_id"' in ttl
    # Payout is owned by payments: defined there, only referenced here.
    assert "<https://x.example/o/payments/Payout>\n" not in ttl
    pay = render_domain_ttl(m, "payments", base="https://x.example/o/")
    assert "<https://x.example/o/payments/Payout>\n" in pay


def test_literals_are_escaped_and_output_is_stable():
    m = derive_business_map(copy.deepcopy(ESTATE))
    ttl = render_domain_ttl(m, "marketplace")
    assert '\\"driver\\"' in ttl and "\\n" in ttl
    again = derive_business_map(list(reversed(copy.deepcopy(ESTATE))))
    assert render_domain_ttl(again, "marketplace") == ttl


def test_suggested_is_left_out_unless_asked():
    m = derive_business_map(copy.deepcopy(ESTATE))
    m["relationships"].append({"from": "Driver", "to": "Trip", "verb": "relates to", "cardinality": "unknown",
                               "state": "inferred", "kind": "reads", "evidence_state": "suggested", "evidence": []})
    assert "Driver_to_Trip" not in render_domain_ttl(m, "marketplace")
    assert "Driver_to_Trip" in render_domain_ttl(m, "marketplace", include_suggested=True)


def test_index_imports_every_domain():
    idx = render_index_ttl(["payments", "marketplace"], base="https://x.example/o/")
    assert "a owl:Ontology" in idx
    assert idx.index("<https://x.example/o/marketplace/>") < idx.index("<https://x.example/o/payments/>")


def test_cli_writes_one_file_per_domain_and_an_index(tmp_path):
    root = tmp_path / "contracts"
    for d, f, body in [
        ("marketplace", "silver_rideflow_riders.yaml", "system: rideflow\nprimary_key: [rider_id]\nmodel:\n  fields:\n    - name: rider_id\n"),
        ("payments", "silver_stripe_charges.yaml", "system: stripe\nprimary_key: [charge_id]\nmodel:\n  fields:\n    - name: charge_id\n    - name: rider_id\n"),
    ]:
        (root / d).mkdir(parents=True)
        (root / d / f).write_text(body, encoding="utf-8")
    r = CliRunner().invoke(app, ["ontology", str(root), "--format", "ttl"])
    assert r.exit_code == 0, r.output
    # Generated files live apart from the authored contracts: ontology/ beside contracts/.
    out = tmp_path / "ontology"
    assert (out / "marketplace.ttl").exists() and (out / "payments.ttl").exists()
    assert "owl:imports" in (out / "index.ttl").read_text(encoding="utf-8")
    assert not list(root.rglob("*.ttl"))
    bad = CliRunner().invoke(app, ["ontology", str(root), "--format", "xml"])
    assert bad.exit_code == 1
